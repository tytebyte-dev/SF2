package io.github.tytebyte_dev.sf2.engine

/**
 * Пороги проверки. Пара фото считается повтором, только если проходит ВСЕ проверки сразу:
 * форма кадра, перцептивные хэши (pHash, dHash), цветовая раскладка и корреляция яркости.
 * Чем «строже» режим, тем меньше шанс принять разные картинки за одну.
 */
enum class Sensitivity(
    val title: String,
    val description: String,
    val maxPHash: Int,
    val maxDHash: Int,
    val minCorrelation: Float,
    val maxColorDiff: Float,
    val maxAspectLog: Double,
) {
    STRICT(
        "Строго",
        "Только то же изображение: копии, пережатые или уменьшенные версии. Ложных находок почти нет, но часть правок можно пропустить.",
        4, 8, 0.97f, 0.06f, 0.02,
    ),
    BALANCED(
        "Сбалансированно",
        "Копии плюс слегка обрезанные, осветлённые или с водяным знаком. Рекомендуемый режим.",
        8, 14, 0.92f, 0.10f, 0.05,
    ),
    LOOSE(
        "Широко",
        "Ищет и очень похожие арты (варианты одной картинки). Возможны лишние находки — смотрите внимательно.",
        12, 20, 0.85f, 0.18f, 0.12,
    ),
}
